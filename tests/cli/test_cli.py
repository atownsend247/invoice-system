def _id_from(output: str, pattern: str) -> str:
    match = re.search(pattern, output)
    assert match, f"pattern {pattern!r} not found in output: {output!r}"
    return match.group(1)


def _base_args(db_path) -> list[str]:
    """`--db`/`--attachments-dir` prefix shared by every invocation below -
    both point at a throwaway tmp_path location so a test run never writes
    into the real repo (see attachments.py's docstring on why uploads
    live on disk, not in SQLite)."""
    return ["--db", str(db_path), "--attachments-dir", str(db_path.parent / "attachments")]


def _demo_user_id(auth_db_path) -> str:
    # The demo user's id is a real UUID4 generated by sessionkit (see
    # CLAUDE.md) - nothing predictable like "1" to hardcode in a test
    # anymore, so this looks it up the same way any real caller would:
    # by email, through sessionkit's own API against the auth db the CLI
    # command was pointed at.
    store = SqliteAuthStore.open(str(auth_db_path))
    try:
        user = AuthService(store).find_user(DEMO_EMAIL)
        assert user is not None
        return user.id
    finally:
        store.close()


def test_storage_dir_alone_lays_out_db_and_attachments_subdirectories(tmp_path):
    # No --db/--attachments-dir override here, unlike every other test in
    # this file (see _base_args) - this is the one test that exercises
    # --storage-dir's own derivation logic end to end.
    storage_dir = tmp_path / "my-storage"
    runner = CliRunner()

    # --no-demo never touches the auth db (see init_db's early return) -
    # this just proves the domain db lands under storage_dir/db/.
    result = runner.invoke(cli, ["--storage-dir", str(storage_dir), "init-db", "--no-demo"])
    assert result.exit_code == 0, result.output
    assert (storage_dir / "db" / "invoice_system.db").exists()

    result = runner.invoke(
        cli,
        [
            "--storage-dir",
            str(storage_dir),
            "account",
            "create",
            "--user-id",
            "1",
            "--business-name",
            "Acme",
            "--email",
            "a@b.test",
            "--address-line1",
            "1 Main St",
        ],
    )
    assert result.exit_code == 0, result.output
    account_id = _id_from(result.output, r"Created account (\S+):")

    result = runner.invoke(
        cli,
        [
            "--storage-dir",
            str(storage_dir),
            "expense",
            "create",
            "--user-id",
            "1",
            "--account-id",
            account_id,
        ],
    )
    assert result.exit_code == 0, result.output
    expense_id = _id_from(result.output, r"Created expense (\S+) \(")

    receipt_path = tmp_path / "receipt.pdf"
    receipt_path.write_bytes(b"%PDF-1.4 fake receipt")
    result = runner.invoke(
        cli,
        [
            "--storage-dir",
            str(storage_dir),
            "expense",
            "attachment",
            "add",
            expense_id,
            "--file",
            str(receipt_path),
            "--user-id",
            "1",
        ],
    )
    assert result.exit_code == 0, result.output

    assert (storage_dir / "db" / "invoice_system.db").exists()
    assert (storage_dir / "attachments").is_dir()
    assert list((storage_dir / "attachments").glob("*.pdf")), "expected an uploaded receipt on disk"


